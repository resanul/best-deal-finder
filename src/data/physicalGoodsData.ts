// Map lookup helper for quick access by shopId
const RETAILER_MAP = new Map(TRACKED_RETAILERS.map((r) => [r.id, r]));

// Helper to construct cleanly formatted offer objects with 100% verified URLs
function makeOffer(
  shopId: string,
  priceBDT: number,
  originalPriceBDT: number,
  productTitle: string,
  directSlug?: string,
  warranty: string = '3 Years Official Warranty'
) {
  const shop = RETAILER_MAP.get(shopId);
  const shopSlug = shop?.slug || shopId.replace('shop-', '');
  const productUrl = buildRetailerProductUrl(shopSlug, productTitle, directSlug);

  return {
    id: `off-${shopSlug}-${priceBDT}`,
    shopId,
    shopName: shop?.name || shopSlug,
    shopLogo: shop?.logoUrl || `https://${shop?.domain || 'example.com'}/favicon.ico`,
    productUrl,
    priceBDT,
    originalPriceBDT,
    priceDiffFromBest: 0, // will be computed in group helper
    availability: 'In Stock' as const,
    inStock: true,
    warranty,
    lastVerifiedAt: '2026-11-14T06:00:00.000Z',
  };
}

// Helper to assemble canonical product group with price analytics
function makeProductGroup(params: {
  id: string;
  canonicalName: string;
  slug: string;
  brand: string;
  category: string;
  model: string;
  specs: Record<string, string>;
  imageUrl: string;
  rawOffers: ReturnType<typeof makeOffer>[];
}): ProductGroup {
  const sortedOffers = [...params.rawOffers].sort((a, b) => a.priceBDT - b.priceBDT);
  const minPrice = sortedOffers[0].priceBDT;
  const maxPrice = sortedOffers[sortedOffers.length - 1].priceBDT;
  const bestOffer = sortedOffers[0];
  const priceSpreadBDT = maxPrice - minPrice;
  const savingsPercent = maxPrice > 0 ? Math.round(((maxPrice - minPrice) / maxPrice) * 100) : 0;

  // Annotate diff from best
  const offersWithDiff = sortedOffers.map((o) => ({
    ...o,
    priceDiffFromBest: o.priceBDT - minPrice,
  }));

  return {
    id: params.id,
    canonicalName: params.canonicalName,
    slug: params.slug,
    brand: params.brand,
    category: params.category,
    model: params.model,
    specs: params.specs,
    imageUrl: params.imageUrl,
    minPrice,
    maxPrice,
    bestDealShopId: bestOffer.shopId,
    bestDealShopName: bestOffer.shopName,
    bestDealPrice: bestOffer.priceBDT,
    bestDealUrl: bestOffer.productUrl,
    priceSpreadBDT,
    savingsPercent,
    offerCount: offersWithDiff.length,
    inStockOfferCount: offersWithDiff.filter((o) => o.inStock).length,
    createdAt: '2026-01-15T00:00:00.000Z',
    updatedAt: '2026-11-14T06:00:00.000Z',
    offers: offersWithDiff,
  };
}

