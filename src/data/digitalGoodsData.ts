/**
 * ============================================================================
 * 5. COMPUTATION HELPERS FOR CONSISTENCY
 * ============================================================================
 */
export function computeProductMetrics(productId: string, deals: VendorDeal[] = initialVendorDeals) {
  const activeDeals = deals.filter(d => d.productId === productId && d.inStock);
  if (activeDeals.length === 0) {
    return { minPrice: 0, maxPrice: 0, offerCount: 0, bestVendorId: '' };
  }

  const sortedDeals = [...activeDeals].sort((a, b) => a.priceBDT - b.priceBDT);
  return {
    minPrice: sortedDeals[0].priceBDT,
    maxPrice: sortedDeals[sortedDeals.length - 1].priceBDT,
    offerCount: activeDeals.length,
    bestVendorId: sortedDeals[0].vendorId
  };
}
